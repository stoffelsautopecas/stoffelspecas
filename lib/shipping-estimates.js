const fold=s=>String(s).normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[-/´']/g,' ').replace(/\s+/g,' ').trim();
export function estimateShipping(product){
 const originalName=fold(product.name);
 const name=originalName.replace(/^(?:par |kit |jogo )(?:de )?/, '').replace(/^bancos\b/,'banco').replace(/^bracos\b/,'braco').replace(/^caixas\b/,'caixa').replace(/^borrachas\b/,'borracha').replace(/^parafusos\b/,'parafuso').replace(/^presilhas\b/,'presilha');
 const category=product.category||product.categorySlug||'';
 let rule=rules.find(([,pattern])=>pattern.test(name));let confidence='medium';
 if(!rule){
  const cat=category.split('/').at(-1);
  const aliases={'macaneta-externa':'door-handle','macaneta-interna':'door-handle','sonda-lambda':'sensor','sensores':'sensor','modulos':'module','botoes':'switch','mangueiras':'hose','acabamentos':'trim','teto':'interior-light','fusiveis':'module'};
  rule=rules.find(([id])=>id===aliases[cat]);confidence='low';
 }
 if(!rule){rule=['unclassified',null,2,45,35,25];confidence='low';}
 const [profile,,kg,length,width,height]=rule;
 let count=/^par\b/.test(originalName)?2:1;
 if(/^jogo\b/.test(originalName)&&['wheel','tyre','hubcap'].includes(profile))count=4;
 const factor=['engine','gearbox','engine-head','differential'].includes(profile)&&/diesel|v6|v8|3\.0|3\.6/.test(name)?1.25:1;
 const heavy=['engine','gearbox','differential','rear-axle','body-structure'].includes(profile);
 const weightGrams=Math.ceil((kg*factor*count+(heavy?12:0.2)+kg*count*0.1)*1000/50)*50;
 const dimensions={lengthCm:Math.ceil(length+4),widthCm:Math.ceil(width+4),heightCm:Math.ceil(height*count+4)};
 const restricted=/\bairbag\b|^bolsa volante|^bateria\b|^tanque combustivel/.test(name);
 return {weightGrams,...dimensions,profile,confidence,estimated:true,reviewRequired:confidence==='low'||heavy||restricted||weightGrams>30000||dimensions.lengthCm>100,restricted,version:ESTIMATE_VERSION};
}
