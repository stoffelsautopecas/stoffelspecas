import assert from 'node:assert/strict';
import { normalizeCart,priceCart,checkoutPayload,validPaymentResult,validatePaymentUrl,createInfinitePayClient } from '../lib/infinitepay.js';
const input=normalizeCart([{id:'311',quantity:1,price:1},{id:'311',quantity:1}]);
assert.deepEqual(input,[{id:311,quantity:2}]);
assert.throws(()=>normalizeCart([{id:'311',quantity:-1}]));
assert.throws(()=>normalizeCart([{id:'311',quantity:1.5}]));
assert.throws(()=>normalizeCart([{id:'311',quantity:99},{id:'311',quantity:1}]));
const product={id:311,name:'Peça de teste',available:true,stockQuantity:2,priceCents:19900};
const items=priceCart(input,[product]);
assert.equal(items[0].unitPriceCents,19900,'Preço do navegador deve ser ignorado');
assert.throws(()=>priceCart(input,[{...product,available:false}]));
assert.throws(()=>priceCart(input,[{...product,stockQuantity:null}]));
assert.throws(()=>priceCart(input,[{...product,stockQuantity:1}]));
assert.throws(()=>priceCart(input,[{...product,priceCents:10000000000}]));
const payload=checkoutPayload({handle:'stoffels',order:{id:'test-order',shippingCents:2500,totalCents:42300},items,redirectUrl:'https://stoffels.vercel.app/pagamento',webhookUrl:'https://stoffels.vercel.app/api/infinitepay-webhook'});
assert.equal(payload.items[0].price,19900);assert.equal(payload.items[1].price,2500);assert.equal(payload.order_nsu,'test-order');
assert.equal(validPaymentResult({success:true,paid:true,amount:42300,paid_amount:44000,capture_method:'credit_card'},42300),true);
assert.equal(validPaymentResult({success:true,paid:true,amount:1,paid_amount:42300,capture_method:'pix'},42300),false);
assert.equal(validPaymentResult({success:true,paid:false,amount:42300,capture_method:'pix'},42300),false);
assert.equal(validPaymentResult({success:true,paid:true,amount:'42300',capture_method:'pix'},42300),false);
assert.throws(()=>validatePaymentUrl('https://infinitepay.io.evil.example/checkout'));
assert.throws(()=>validatePaymentUrl('http://checkout.infinitepay.io/test'));
assert.throws(()=>validatePaymentUrl('javascript:alert(1)'));
const requests=[];
const fakeFetch=async(url,init)=>{requests.push({url,body:JSON.parse(init.body)});return {ok:true,json:async()=>url.endsWith('/links')?{checkout_url:'https://checkout.infinitepay.io/stoffels/test-slug'}:{success:true,paid:true,amount:42300,capture_method:'pix'}};};
const client=createInfinitePayClient(fakeFetch);assert.equal((await client.createLink(payload)).url,'https://checkout.infinitepay.io/stoffels/test-slug');
const payment=await client.checkPayment({handle:'stoffels',orderId:'test-order',transactionNsu:'test-transaction',slug:'test-slug'});
assert.ok(validPaymentResult(payment,42300));assert.equal(requests[1].body.order_nsu,'test-order');
console.log('InfinitePay: preço no servidor, estoque, centavos, frete, links e confirmação de valores verificados. Nenhuma chamada real ou cobrança foi realizada.');
